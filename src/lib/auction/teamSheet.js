// Downloadable team sheets: one page per team, with every player's photo, name,
// category and the coins they cost. Built for printing and sharing once the
// auction is over.
import { jsPDF } from 'jspdf';
import { initials, contrastText } from '@/components/auction/Shared';
import { teamFinance } from './squad';

const COLORS = {
  page: [15, 23, 42],
  card: [30, 41, 59],
  line: [51, 65, 85],
  white: [255, 255, 255],
  muted: [148, 163, 184],
  emerald: [16, 185, 129],
  emeraldLight: [52, 211, 153],
  purple: [192, 132, 252],
};

const ROW = 30;
const AVATAR = 20;

const slugify = (value) =>
  String(value || 'auction')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '') || 'auction';

const loadImage = (src) =>
  new Promise((resolve) => {
    if (!src) return resolve(null);
    const img = new Image();
    img.crossOrigin = 'anonymous';
    img.onload = () => resolve(img);
    img.onerror = () => resolve(null);
    img.src = src;
  });

function roundPath(ctx, x, y, w, h, r) {
  const radius = Math.min(r, w / 2, h / 2);
  ctx.beginPath();
  ctx.moveTo(x + radius, y);
  ctx.arcTo(x + w, y, x + w, y + h, radius);
  ctx.arcTo(x + w, y + h, x, y + h, radius);
  ctx.arcTo(x, y + h, x, y, radius);
  ctx.arcTo(x, y, x + w, y, radius);
  ctx.closePath();
}

// A square player icon drawn on its own canvas: the photo when there is one,
// otherwise the player's initials on the team colour.
function avatarCanvas(img, name, color) {
  const S = 160;
  const canvas = document.createElement('canvas');
  canvas.width = S;
  canvas.height = S;
  const ctx = canvas.getContext('2d');

  ctx.save();
  roundPath(ctx, 0, 0, S, S, 34);
  ctx.clip();
  ctx.fillStyle = '#1e293b';
  ctx.fillRect(0, 0, S, S);

  if (img) {
    const ratio = Math.max(S / img.width, S / img.height);
    const w = img.width * ratio;
    const h = img.height * ratio;
    ctx.drawImage(img, (S - w) / 2, (S - h) / 2, w, h);
  } else {
    ctx.fillStyle = color || '#10b981';
    ctx.fillRect(0, 0, S, S);
    ctx.fillStyle = contrastText(color || '#10b981');
    ctx.font = 'bold 62px Helvetica, Arial, sans-serif';
    ctx.textAlign = 'center';
    ctx.textBaseline = 'middle';
    ctx.fillText(initials(name), S / 2, S / 2 + 3);
  }
  ctx.restore();
  return canvas;
}

export async function downloadTeamSheets({ tournament, teams = [], players = [], settings }) {
  const doc = new jsPDF({ unit: 'pt', format: 'a4', orientation: 'portrait' });
  const W = doc.internal.pageSize.getWidth();
  const H = doc.internal.pageSize.getHeight();
  const M = 40;
  const inner = W - M * 2;
  const purse = Number(settings?.purse) || 0;
  const BOTTOM = H - 56;

  const clip = (text, width) => {
    let value = String(text ?? '');
    if (doc.getTextWidth(value) <= width) return value;
    while (value.length > 1 && doc.getTextWidth(`${value}…`) > width) value = value.slice(0, -1);
    return `${value}…`;
  };

  const paintPage = () => {
    doc.setFillColor(...COLORS.page);
    doc.rect(0, 0, W, H, 'F');
    doc.setFillColor(...COLORS.emerald);
    doc.rect(0, 0, W, 3, 'F');
  };

  const masthead = () => {
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(11);
    doc.setTextColor(...COLORS.white);
    doc.text('CrickTrack', M, 32);

    doc.setFont('helvetica', 'normal');
    doc.setFontSize(7);
    doc.setTextColor(...COLORS.muted);
    doc.text('TAG  |  ANALYSE  |  ELEVATE', M, 43);

    doc.setFontSize(7.5);
    doc.setTextColor(...COLORS.emeraldLight);
    doc.text('TEAM SHEET', W - M, 32, { align: 'right' });
    doc.setTextColor(...COLORS.muted);
    doc.text(clip(tournament?.name || 'Auction', 220), W - M, 43, { align: 'right' });
    return 78;
  };

  const footer = () => {
    const pages = doc.getNumberOfPages();
    for (let p = 1; p <= pages; p += 1) {
      doc.setPage(p);
      doc.setDrawColor(...COLORS.line);
      doc.setLineWidth(0.6);
      doc.line(M, H - 44, W - M, H - 44);
      doc.setFont('helvetica', 'normal');
      doc.setFontSize(7.5);
      doc.setTextColor(...COLORS.muted);
      doc.text('Squads after the auction  ·  generated by CrickTrack', M, H - 30);
      doc.setTextColor(...COLORS.emeraldLight);
      doc.text(`cricktrack.com   ·   ${p} / ${pages}`, W - M, H - 30, { align: 'right' });
    }
  };

  if (!teams.length) {
    paintPage();
    const y = masthead();
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(9);
    doc.setTextColor(...COLORS.muted);
    doc.text('No teams have been added to this auction yet.', M, y);
    footer();
    doc.save(`${slugify(tournament?.name)}-team-sheets.pdf`);
    return;
  }

  for (let i = 0; i < teams.length; i += 1) {
    const team = teams[i];
    const finance = teamFinance({ teamId: team.id, players, settings });
    const squad = finance.squad;
    const color = team.color || '#10b981';

    const [logoImg, ...photoList] = await Promise.all([
      loadImage(team.logo_url),
      ...squad.map((p) => loadImage(p.photo_url)),
    ]);
    const photoFor = new Map(squad.map((p, idx) => [p.id, photoList[idx]]));

    if (i > 0) doc.addPage();
    paintPage();
    let y = masthead();

    // ---- team header ----
    const badge = avatarCanvas(logoImg, team.name, color);
    doc.addImage(badge.toDataURL('image/png'), 'PNG', M, y, 46, 46);

    doc.setFont('helvetica', 'bold');
    doc.setFontSize(18);
    doc.setTextColor(...COLORS.white);
    doc.text(clip(team.name, inner - 70), M + 58, y + 20);

    doc.setFont('helvetica', 'normal');
    doc.setFontSize(8.5);
    doc.setTextColor(...COLORS.muted);
    const facts = [
      `${squad.length}/${finance.target} players`,
      `${finance.spent} coins spent`,
      `${finance.purseLeft} left`,
    ];
    if (purse) facts.push(`purse ${purse}`);
    doc.text(facts.join('   ·   '), M + 58, y + 35);

    y += 60;

    // The two biggest buys sit at the foot of the page, so their space is
    // reserved before the player list is measured — one page per team.
    const buys = squad
      .filter((p) => p.category !== 'icon' && Number(p.sold_price) > 0)
      .sort((a, b) => Number(b.sold_price) - Number(a.sold_price))
      .slice(0, 2);
    const listBottom = BOTTOM - (buys.length ? 196 : 0);

    // ---- column headings ----
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(7);
    doc.setTextColor(...COLORS.muted);
    doc.text('PLAYER', M + 34, y);
    doc.text('CATEGORY', M + inner - 120, y);
    doc.text('COINS', M + inner, y, { align: 'right' });
    y += 6;
    doc.setDrawColor(...COLORS.line);
    doc.setLineWidth(0.6);
    doc.line(M, y, M + inner, y);
    y += 8;

    if (!squad.length) {
      doc.setFont('helvetica', 'italic');
      doc.setFontSize(9);
      doc.setTextColor(...COLORS.muted);
      doc.text('No players in this squad yet.', M, y + 12);
    }

    // Rows shrink to whatever space the biggest-buys block leaves, so a full
    // squad still fits on this one page.
    const rowH = squad.length
      ? Math.min(ROW, Math.max(12, (listBottom - y) / squad.length))
      : ROW;
    const avatarSize = Math.min(AVATAR, Math.max(10, rowH - 8));
    const nameSize = rowH < 18 ? 8.5 : rowH < 24 ? 9.5 : 10;

    squad.forEach((p) => {
      const avatar = avatarCanvas(photoFor.get(p.id), p.name, color);
      doc.addImage(
        avatar.toDataURL('image/png'),
        'PNG',
        M,
        y + (rowH - avatarSize) / 2,
        avatarSize,
        avatarSize
      );

      const mid = y + rowH / 2 + 3;

      doc.setFont('helvetica', 'bold');
      doc.setFontSize(nameSize);
      doc.setTextColor(...COLORS.white);
      doc.text(clip(p.name, inner - 190), M + 34, mid);

      const isIcon = p.category === 'icon';
      doc.setFont('helvetica', 'normal');
      doc.setFontSize(8);
      doc.setTextColor(...(isIcon ? COLORS.purple : COLORS.muted));
      doc.text(String(p.category || '—').toUpperCase(), M + inner - 120, mid);

      doc.setFont('helvetica', 'bold');
      doc.setFontSize(nameSize);
      doc.setTextColor(...COLORS.emeraldLight);
      // A team added after the auction never bid, so its coins column stays empty;
      // a backup player filled no slot and cost nothing, so it reads EXTRA.
      doc.text(
        isIcon
          ? 'ICON'
          : p.is_extra
            ? 'EXTRA'
            : team.post_auction
              ? ''
              : String(Number(p.sold_price) || 0),
        M + inner,
        mid,
        { align: 'right' }
      );

      y += rowH;
      doc.setDrawColor(40, 52, 72);
      doc.setLineWidth(0.4);
      doc.line(M, y - 5, M + inner, y - 5);
    });

    // ---- the two biggest buys, big photos ----
    if (buys.length) {
      let by = listBottom + 2;

      doc.setFont('helvetica', 'bold');
      doc.setFontSize(7);
      doc.setTextColor(...COLORS.muted);
      doc.text('BIGGEST BUYS', M, by + 8);

      doc.setDrawColor(...COLORS.line);
      doc.setLineWidth(0.6);
      doc.line(M, by + 14, M + inner, by + 14);
      by += 22;

      const gap = 16;
      const cardW = (inner - gap * (buys.length - 1)) / buys.length;
      const side = Math.min(cardW - 24, 112);
      const cardH = side + 58;

      buys.forEach((p, idx) => {
        const x = M + idx * (cardW + gap);
        const cx = x + cardW / 2;

        doc.setFillColor(...COLORS.card);
        doc.roundedRect(x, by, cardW, cardH, 8, 8, 'F');

        const photo = avatarCanvas(photoFor.get(p.id), p.name, color);
        doc.addImage(
          photo.toDataURL('image/png'),
          'PNG',
          x + (cardW - side) / 2,
          by + 12,
          side,
          side
        );

        doc.setFont('helvetica', 'bold');
        doc.setFontSize(10);
        doc.setTextColor(...COLORS.white);
        doc.text(clip(p.name, cardW - 20), cx, by + side + 28, { align: 'center' });

        doc.setFontSize(14);
        doc.setTextColor(...COLORS.emeraldLight);
        doc.text(String(Number(p.sold_price) || 0), cx, by + side + 46, { align: 'center' });

        doc.setFont('helvetica', 'normal');
        doc.setFontSize(6.5);
        doc.setTextColor(...COLORS.muted);
        doc.text('COINS', cx, by + side + 56, { align: 'center' });
      });
    }
  }

  footer();
  doc.save(`${slugify(tournament?.name)}-team-sheets.pdf`);
}