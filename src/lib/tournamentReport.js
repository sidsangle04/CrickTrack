// Printable tournament statistical report. Opened in a new window with print
// styles so it can be saved as a PDF from the browser's print dialog.

const esc = (v) =>
  String(v ?? '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;');

const table = (head, rows) => `
  <table>
    <thead><tr>${head.map((h) => `<th>${esc(h)}</th>`).join('')}</tr></thead>
    <tbody>${rows.map((r) => `<tr>${r.map((c) => `<td>${esc(c)}</td>`).join('')}</tr>`).join('')}</tbody>
  </table>`;

export function buildTournamentReport(stats, tournament) {
  const { overview, pointsTable, batting, bowling, fielding, records } = stats;

  const recordRows = Object.entries(records)
    .filter(([, r]) => r)
    .map(([key, r]) => [
      key.replace(/_/g, ' ').replace(/\b\w/g, (c) => c.toUpperCase()),
      r.value,
      r.name,
      r.match || '',
    ]);

  return `<!DOCTYPE html>
<html lang="en"><head><meta charset="utf-8" />
<title>${esc(tournament?.name || 'Tournament')} — statistics</title>
<style>
  *{box-sizing:border-box;margin:0;padding:0}
  body{font-family:-apple-system,BlinkMacSystemFont,'Segoe UI',sans-serif;color:#0f172a;padding:28px;font-size:12px}
  h1{font-size:22px;font-weight:800;margin-bottom:2px}
  .sub{color:#64748b;font-size:11px;margin-bottom:18px}
  h2{font-size:13px;text-transform:uppercase;letter-spacing:.06em;color:#059669;margin:22px 0 8px}
  .grid{display:grid;grid-template-columns:repeat(5,1fr);gap:8px;margin-bottom:6px}
  .stat{border:1px solid #e2e8f0;border-radius:8px;padding:8px}
  .stat b{display:block;font-size:16px}
  .stat span{font-size:9px;color:#64748b;text-transform:uppercase;letter-spacing:.04em}
  table{width:100%;border-collapse:collapse;font-size:10.5px}
  th{text-align:left;background:#f1f5f9;padding:5px 6px;border-bottom:1px solid #cbd5e1;font-weight:600}
  td{padding:5px 6px;border-bottom:1px solid #e2e8f0}
  tr:nth-child(even) td{background:#f8fafc}
  footer{margin-top:20px;font-size:9px;color:#94a3b8}
  @media print{body{padding:12px}}
</style></head><body>
<h1>${esc(tournament?.name || 'Tournament')}</h1>
<div class="sub">Tournament statistics · ${overview.matches} completed ${
    overview.matches === 1 ? 'match' : 'matches'
  } · generated ${new Date().toLocaleDateString('en-GB', { day: 'numeric', month: 'long', year: 'numeric' })}</div>

<div class="grid">
  ${[
    ['Matches', overview.matches],
    ['Runs', overview.runs],
    ['Wickets', overview.wickets],
    ['Overs', overview.overs],
    ['Avg / match', overview.average_per_match ?? '—'],
    ['Fours', overview.fours],
    ['Sixes', overview.sixes],
    ['Highest team', overview.highest_team_score?.value || '—'],
    ['Highest score', overview.highest_individual?.value || '—'],
    ['Best bowling', overview.best_bowling?.value || '—'],
  ]
    .map(([l, v]) => `<div class="stat"><b>${esc(v)}</b><span>${esc(l)}</span></div>`)
    .join('')}
</div>

<h2>Points table</h2>
${table(
  ['#', 'Team', 'P', 'W', 'L', 'T', 'NR', 'Pts', 'NRR'],
  pointsTable.map((t, i) => [
    i + 1,
    t.name,
    t.played,
    t.won,
    t.lost,
    t.tied,
    t.no_result,
    t.points,
    t.nrr === null ? '—' : t.nrr.toFixed(3),
  ])
)}

<h2>Batting</h2>
${table(
  ['#', 'Player', 'Team', 'M', 'Inn', 'Runs', 'Balls', 'HS', 'Avg', 'SR', '4s', '6s', '30s', '50s'],
  [...batting]
    .sort((a, b) => b.runs - a.runs)
    .slice(0, 25)
    .map((p, i) => [
      i + 1,
      p.name,
      p.team_name,
      p.matches,
      p.innings,
      p.runs,
      p.balls,
      p.hs_text,
      p.average ?? '—',
      p.strike_rate ?? '—',
      p.fours,
      p.sixes,
      p.thirties,
      p.fifties,
    ])
)}

<h2>Bowling</h2>
${table(
  ['#', 'Player', 'Team', 'Overs', 'Runs', 'Wkts', 'Best', 'Avg', 'Econ', 'SR', 'Dots', 'Mdns'],
  [...bowling]
    .sort((a, b) => b.wickets - a.wickets || b.best_sort - a.best_sort)
    .slice(0, 25)
    .map((p, i) => [
      i + 1,
      p.name,
      p.team_name,
      p.overs,
      p.runs,
      p.wickets,
      p.best_text,
      p.average ?? '—',
      p.economy ?? '—',
      p.strike_rate ?? '—',
      p.dots,
      p.maidens,
    ])
)}

<h2>Fielding</h2>
${table(
  ['#', 'Player', 'Team', 'Catches', 'Run-outs', 'Stumpings', 'Total'],
  [...fielding]
    .sort((a, b) => b.total - a.total)
    .slice(0, 15)
    .map((p, i) => [i + 1, p.name, p.team_name, p.catches, p.run_outs, p.stumpings, p.total])
)}

<h2>Tournament records</h2>
${table(['Record', 'Value', 'Name', 'Match'], recordRows)}

<footer>Generated by CrickTrack — every figure is calculated from recorded match data.</footer>
</body></html>`;
}

export function openTournamentReport(stats, tournament) {
  const win = window.open('', '_blank');
  if (!win) return false;
  win.document.write(buildTournamentReport(stats, tournament));
  win.document.close();
  win.focus();
  setTimeout(() => win.print(), 500);
  return true;
}